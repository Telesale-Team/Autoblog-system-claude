class Command(BaseCommand):
    help = "สร้าง/อัปเดตรายการ AI-slop ภาษาไทย สำหรับให้คณะกรรมการใช้ตรวจบทความ"

    def add_arguments(self, parser):
        parser.add_argument("--reset", action="store_true",
                            help="เขียนทับรายการที่มีอยู่ (ค่าที่แก้ไว้เองจะหายไป)")

    def handle(self, *args, **options):
        reset = options["reset"]
        created = updated = skipped = 0

        for data in PATTERNS:
            existing = SP.objects.filter(pattern=data["pattern"]).first()
            if existing is None:
                SP.objects.create(**data)
                created += 1
            elif reset:
                for field, value in data.items():
                    setattr(existing, field, value)
                existing.save()
                updated += 1
            else:
                skipped += 1

        by_kind = {}
        for kind, label in SP.Kind.choices:
            by_kind[label] = SP.objects.filter(kind=kind, is_active=True).count()

        self.stdout.write(self.style.SUCCESS(
            "สร้าง %d · เขียนทับ %d · ข้าม %d" % (created, updated, skipped)))
        for label, n in by_kind.items():
            self.stdout.write("   %-22s %d" % (label, n))
        self.stdout.write(self.style.SUCCESS(
            "รวมในระบบ %d รายการ" % SP.objects.count()))
